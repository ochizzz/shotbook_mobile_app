"""Writes the bundled (offline) catalog from catalog rows.

Usage: gen_seed.py <rows.json> lib/features/discover/data/seed_photo_references.dart
Rows use the Supabase `photos` shape (see supabase/seed/unsplash_batch_01.json).
"""
import json, sys

order = ['Portrait', 'Street', 'Full Body', 'Night', 'Lifestyle', 'Car', 'Couple', 'Product']
rows = sorted(json.load(open(sys.argv[1])), key=lambda r: r['sort_order'])


def d(s):
    if s is None:
        return 'null'
    s = str(s)
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def m(obj, ind):
    pad = ' ' * ind
    if isinstance(obj, dict):
        if not obj:
            return 'const {}'
        return '{\n' + ''.join(f"{pad}  {d(k)}: {m(v, ind + 2)},\n" for k, v in obj.items()) + pad + '}'
    return d(obj)


def orig(o):
    if not o:
        return ''
    return (f"    original: OriginalShot(\n"
            f"      camera: {d(o.get('camera'))},\n"
            f"      focalMm: {float(o['focal_mm'])},\n"
            f"      equivMm: {float(o['equiv_mm'])},\n"
            f"      aperture: {float(o['aperture'])},\n"
            f"      seconds: {seconds(o['shutter'])},\n"
            f"      iso: {int(o['iso'])},\n"
            f"    ),")


def seconds(text):
    text = str(text)
    if '/' in text:
        a, b = text.split('/')
        return float(a) / float(b)
    return float(text)


out = [
    '// GENERATED by tool/gen_seed.py from supabase/seed/unsplash_batch_*.json.',
    '// Photos from Unsplash (hotlinked, attributed) with phone recipes.',
    '// The same rows live in Supabase; this list is the offline fallback.',
    "import '../../recipe/recipe_engine.dart';",
    "import '../domain/photo_reference.dart';",
    '',
    'const photoCategories = [\n  \'All\',\n' + ''.join(f"  '{c}',\n" for c in order) + '];',
    '',
    'const seedPhotoReferences = <PhotoReference>[',
]
for x in rows:
    out.append(f"""  PhotoReference(
    id: {d(x['legacy_id'])},
    unsplashId: {d(x.get('unsplash_id'))},
    title: {d(x['title'])},
    description: {d(x['description'])},
    imageUrl: {d(x['image_url'])},
    thumbUrl: {d(x['thumb_url'])},
    category: {d(x['category'])},
    sourcePage: {d(x['source_page'])},
    credit: {d(x['credit'])},
    creatorUrl: {d(x.get('creator_url'))},
    license: {d(x['license'])},
    licenseUrl: {d(x.get('license_url'))},
    deviceId: {d(x['device_id'])},
    device: {d(x['device'])},
    camera: {d(x['camera'])},
    focalLength: {d(x['focal_length'])},
    iso: {d(x['iso'])},
    shutterSpeed: {d(x['shutter_speed'])},
    aperture: {d(x['aperture'])},
    whiteBalance: {d(x['white_balance'])},
    exposureCompensation: {d(x['exposure_compensation'])},
    poseData: {m(x['pose_data'], 4)},
    editingData: {m(x['editing_data'], 4)},
    imageAspectRatio: {x['aspect_ratio']},
{orig(x.get('original_shot'))}
    translations: {{
      'en': {m(x['translations']['en'], 6)},
    }},
  ),""")
out.append('];')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(rows))
